"""Deterministic filtering and held-out n-gram contamination checks."""

import hashlib
import re
from collections import Counter
from collections.abc import Iterable
from dataclasses import dataclass


def content_hash(text: str) -> str:
    return hashlib.sha256(text.encode("utf-8")).hexdigest()


def words(text: str) -> list[str]:
    return re.findall(r"\w+", text.casefold())


class ContaminationIndex:
    def __init__(self, held_out: Iterable[str], n: int = 13) -> None:
        if n < 1:
            raise ValueError("n must be positive")
        self.n = n
        self.ngrams: dict[int, set[tuple[str, ...]]] = {}
        for text in held_out:
            tokens = words(text)
            size = min(n, len(tokens))
            if size:
                self.ngrams.setdefault(size, set()).update(
                    tuple(tokens[i : i + size]) for i in range(len(tokens) - size + 1)
                )

    def contains(self, text: str) -> bool:
        tokens = words(text)
        return any(
            tuple(tokens[i : i + size]) in ngrams
            for size, ngrams in self.ngrams.items()
            for i in range(len(tokens) - size + 1)
        )


@dataclass(frozen=True)
class Document:
    id: str
    source: str
    text: str
    domain: str


@dataclass(frozen=True)
class FilterConfig:
    min_bytes: int = 32
    max_bytes: int = 1024 * 1024
    max_line_length: int = 1000
    min_alphanumeric_share: float = 0.1

    def __post_init__(self) -> None:
        if not 0 <= self.min_bytes <= self.max_bytes or self.max_line_length < 1:
            raise ValueError("invalid filter sizes")
        if not 0 <= self.min_alphanumeric_share <= 1:
            raise ValueError("invalid alphanumeric share")


def filter_documents(
    documents: Iterable[Document],
    contamination: ContaminationIndex,
    config: FilterConfig | None = None,
) -> tuple[list[Document], dict[str, dict[str, int]]]:
    """Count one primary rejection reason per document, separately by source."""
    config = config or FilterConfig()
    seen: set[str] = set()
    kept: list[Document] = []
    report: dict[str, Counter[str]] = {}
    for document in documents:
        counts = report.setdefault(document.source, Counter())
        counts["seen"] += 1
        text = document.text
        size = len(text.encode("utf-8"))
        digest = content_hash(text)
        reason = "kept"
        if document.domain not in {"web", "python"}:
            reason = "unknown_domain"
        elif size < config.min_bytes:
            reason = "too_short"
        elif size > config.max_bytes:
            reason = "too_large"
        elif (
            document.domain == "python"
            and max(map(len, text.splitlines()), default=0) > config.max_line_length
        ):
            reason = "long_line"
        elif (
            document.domain == "python"
            and sum(ch.isalnum() for ch in text) / max(len(text), 1) < config.min_alphanumeric_share
        ):
            reason = "low_alphanumeric"
        elif document.domain == "python" and any(
            marker in text.casefold()
            for marker in ("auto-generated", "autogenerated", "do not edit")
        ):
            reason = "generated"
        elif digest in seen:
            reason = "duplicate"
        elif contamination.contains(text):
            reason = "contamination"
        counts[reason] += 1
        if reason == "kept":
            seen.add(digest)
            kept.append(document)
    return kept, {source: dict(counts) for source, counts in report.items()}


def document_split(identifier: str, *, web: bool = False) -> str:
    """Stable hash allocation independent of input order and Python hash seeds."""
    value = int(hashlib.sha256(identifier.encode()).hexdigest()[:16], 16) / 2**64
    if value < 0.005:
        return "validation"
    if web and value < 0.105:
        return "stage2"
    return "stage1" if web else "train"
