"""Local RL screening commands: the static pre-screen and scoring screening attempts.

``prescreen_candidates`` reads the pool's train tasks and the RL candidate list and counts
the rules that need no generation (parseable hidden tests, constant baseline below the
threshold). It runs no code. ``screen_attempts`` scores a JSONL file of screening attempts
(``Attempt.to_json`` per line, as generated by ``screening_rollouts``) through
``LocalRewardSource`` in the Docker sandbox and writes the screening record. Both refuse a
candidate that is not a train task.

A file the post-training Pod worker wrote starts with a header (``scratchcoder.rl.attempts``)
naming the task file it was generated from: on a Pod, the candidates export with the hidden
tests removed. ``screen_attempts`` then checks the header's sampling against the screening
protocol and the candidate file's SHA-256, derives the export from the full train file again
to compare SHA-256s, and every candidate must have exactly the header's samples.
``require_header`` refuses a file without one.
"""

from __future__ import annotations

from collections.abc import Mapping, Sequence
from pathlib import Path
from typing import Any

from scratchcoder.common.records import atomic_json
from scratchcoder.eval.export import (
    ExportError,
    candidate_tasks,
    file_sha256,
    refuse_exported,
    task_file_identity,
)
from scratchcoder.eval.tasks import Task
from scratchcoder.rl.attempts import (
    SCREENING_PROTOCOL,
    ScreeningHeader,
    check_grid,
    check_protocol,
    read_attempts_file,
)
from scratchcoder.rl.rewards import Attempt, LocalRewardSource
from scratchcoder.rl.screening import (
    DEFAULT_THRESHOLD,
    FLOOR,
    MAX_KEPT,
    prescreen,
    score_screening,
    screen,
)


def read_candidates(tasks_path: Path, candidates_path: Path) -> list[Task]:
    """The candidate tasks, in candidate-file order, each checked against its listed source."""
    return candidate_tasks(tasks_path, candidates_path)


def prescreen_candidates(
    tasks_path: Path, candidates_path: Path, *, threshold: float = DEFAULT_THRESHOLD
) -> dict[str, Any]:
    return prescreen(read_candidates(tasks_path, candidates_path), threshold=threshold)


def read_attempts(path: Path) -> list[Attempt]:
    """The attempts of a screening file, with or without its header line."""
    return read_attempts_file(path)[1]


def check_attempts_header(
    header: ScreeningHeader,
    attempts: Sequence[Attempt],
    tasks: Sequence[Task],
    *,
    tasks_path: Path,
    candidates_path: Path,
    protocol: Mapping[str, int | float] = SCREENING_PROTOCOL,
) -> str:
    """Bind a header to the given files; return ``"file"`` or ``"export"`` (what it names).

    The header's sampling must be the screening protocol's (``check_protocol``). The
    candidate file must hash to the header's ``candidates_sha256``. The header's task file
    must be the given train file itself or the candidates export derived from it again; the
    export's record is never read. Every candidate must have exactly the header's samples.
    """
    check_protocol(header, protocol)
    if file_sha256(candidates_path) != header.candidates_sha256:
        raise ValueError("the candidate file's SHA-256 differs from the screening header")
    try:
        identity = task_file_identity(
            tasks_path, header.task_file_sha256, candidates_path=candidates_path
        )
    except ExportError as error:
        raise ValueError(
            f"the screening attempts were not generated from {tasks_path}: {error}"
        ) from error
    check_grid(header, attempts, [task.id for task in tasks])
    return identity


def screen_attempts(
    *,
    tasks_path: Path,
    candidates_path: Path,
    attempts_path: Path,
    output: Path,
    timeout: float | None,
    workers: int = 8,
    threshold: float = DEFAULT_THRESHOLD,
    cap: int = MAX_KEPT,
    floor: int = FLOOR,
    require_header: bool = False,
) -> dict[str, Any]:
    """Score screening attempts in the sandbox and write the screening record to ``output``.

    ``timeout`` bounds each batch of 256 attempts (``None`` for no bound). A header is
    checked against the given files before any attempt runs (``check_attempts_header``).
    """
    if output.exists():
        raise ValueError(f"{output} already exists")
    tasks = read_candidates(tasks_path, candidates_path)
    refuse_exported(tasks, tasks_path)  # Rewards need the real hidden tests.
    header, attempts = read_attempts_file(attempts_path)
    identity = None
    if header is not None:
        identity = check_attempts_header(
            header, attempts, tasks, tasks_path=tasks_path, candidates_path=candidates_path
        )
    elif require_header:
        raise ValueError(f"{attempts_path} has no screening header; it cannot be bound to tasks")
    source = LocalRewardSource(tasks, timeout=timeout, workers=workers)
    rewards = score_screening(source, attempts)
    result = screen(tasks, attempts, rewards, threshold=threshold, cap=cap, floor=floor)
    record = result.to_json()
    record["inputs"] = {
        "tasks": str(tasks_path),
        "candidates": str(candidates_path),
        "attempts": str(attempts_path),
        "attempts_sha256": file_sha256(attempts_path),
        "header": None if header is None else header.to_json(),
        "header_task_file": identity,
    }
    record["rewards"] = [
        {"task_id": attempt.task_id, "sample": attempt.sample, **reward.to_json()}
        for attempt, reward in zip(attempts, rewards, strict=True)
    ]
    atomic_json(output, record)
    return {"outcome": result.outcome, **result.counts()}
