"""Local RL screening commands: the static pre-screen and scoring screening attempts.

``prescreen_candidates`` reads the pool's train tasks and the RL candidate list and counts
the rules that need no generation (parseable hidden tests, constant baseline below the
threshold). It runs no code. ``screen_attempts`` scores a JSONL file of screening attempts
(``Attempt.to_json`` per line, as generated by ``screening_rollouts``) through
``LocalRewardSource`` in the Docker sandbox and writes the screening record. Both refuse a
candidate that is not a train task.
"""

from __future__ import annotations

import json
from pathlib import Path
from typing import Any

from scratchcoder.common.records import atomic_json
from scratchcoder.eval.tasks import Task, load_tasks
from scratchcoder.rl.rewards import Attempt, LocalRewardSource
from scratchcoder.rl.screening import (
    DEFAULT_THRESHOLD,
    FLOOR,
    MAX_KEPT,
    prescreen,
    score_screening,
    screen,
)


def read_candidates(tasks_path: Path, candidates_path: Path) -> list[Task]:
    """The candidate tasks, in candidate-file order, each checked against its listed source."""
    listed: list[tuple[str, str]] = []
    for number, line in enumerate(candidates_path.read_text(encoding="utf-8").splitlines(), 1):
        if not line.strip():
            continue
        row = json.loads(line)
        if not isinstance(row, dict) or set(row) != {"id", "source"}:
            raise ValueError(f"candidate line {number} needs exactly id and source")
        listed.append((row["id"], row["source"]))
    if len({identifier for identifier, _ in listed}) != len(listed):
        raise ValueError("candidate IDs must be unique")
    wanted = {identifier for identifier, _ in listed}
    found = {task.id: task for task in load_tasks(tasks_path) if task.id in wanted}
    missing = sorted(wanted - set(found))
    if missing:
        raise ValueError(f"{len(missing)} candidates are not in the task file, e.g. {missing[0]}")
    tasks = [found[identifier] for identifier, _ in listed]
    for task, (_, source) in zip(tasks, listed, strict=True):
        if task.split != "train":
            raise ValueError(f"candidate {task.id} is not a train task")
        if task.source != source:
            raise ValueError(f"candidate {task.id} is listed under another source")
    return tasks


def prescreen_candidates(
    tasks_path: Path, candidates_path: Path, *, threshold: float = DEFAULT_THRESHOLD
) -> dict[str, Any]:
    return prescreen(read_candidates(tasks_path, candidates_path), threshold=threshold)


def read_attempts(path: Path) -> list[Attempt]:
    return [
        Attempt.from_json(json.loads(line))
        for line in path.read_text(encoding="utf-8").splitlines()
        if line.strip()
    ]


def screen_attempts(
    *,
    tasks_path: Path,
    candidates_path: Path,
    attempts_path: Path,
    output: Path,
    timeout: float | None,
    workers: int = 8,
    threshold: float = DEFAULT_THRESHOLD,
    cap: int = MAX_KEPT,
    floor: int = FLOOR,
) -> dict[str, Any]:
    """Score screening attempts in the sandbox and write the screening record to ``output``.

    ``timeout`` bounds each batch of 256 attempts (``None`` for no bound).
    """
    if output.exists():
        raise ValueError(f"{output} already exists")
    tasks = read_candidates(tasks_path, candidates_path)
    attempts = read_attempts(attempts_path)
    source = LocalRewardSource(tasks, timeout=timeout, workers=workers)
    rewards = score_screening(source, attempts)
    result = screen(tasks, attempts, rewards, threshold=threshold, cap=cap, floor=floor)
    record = result.to_json()
    record["inputs"] = {
        "tasks": str(tasks_path),
        "candidates": str(candidates_path),
        "attempts": str(attempts_path),
    }
    record["rewards"] = [
        {"task_id": attempt.task_id, "sample": attempt.sample, **reward.to_json()}
        for attempt, reward in zip(attempts, rewards, strict=True)
    ]
    atomic_json(output, record)
    return {"outcome": result.outcome, **result.counts()}
